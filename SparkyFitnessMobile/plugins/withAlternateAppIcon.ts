// Registers the "Dark" alternate app icon (Settings > App Icon) so it is
// selectable independent of the system Light/Dark/Tinted appearance, which
// the primary Icon Composer icon already follows on its own and which no
// API lets an app override. This is a second, named icon under Info.plist's
// CFBundleIcons.CFBundleAlternateIcons, switched at runtime via
// UIApplication.setAlternateIconName (see
// modules/alternate-app-icon/ios/AlternateAppIconModule.swift).
//
// The source artwork is a plain asset-catalog "App Icon" image set (one
// 1024x1024 universal image; Xcode derives every size from it), generated by
// brand/generate-icons.py into assets/icons/alt-icon-dark.appiconset/. It is
// copied into the main app target's own Images.xcassets at prebuild — no
// Xcode project surgery is needed, since an asset catalog is one folder
// reference in the project and Xcode's catalog compiler auto-discovers any
// new .appiconset subfolder inside it (SplashScreenLogo.imageset and the
// others already work this way).
import {
  ConfigPlugin,
  IOSConfig,
  withDangerousMod,
  withInfoPlist,
  withXcodeProject,
} from 'expo/config-plugins';
import fs from 'fs';
import path from 'path';

// Must match the `AlternateAppIconName` key used in
// modules/alternate-app-icon/index.ts.
const DARK_APP_ICON_NAME = 'Dark';
const DARK_ICON_ASSET_SET_NAME = 'AppIcon-Dark';
const SOURCE_DIR_NAME = 'assets/icons/alt-icon-dark.appiconset';

const withAlternateAppIcon: ConfigPlugin = (config) => {
  config = withDangerousMod(config, [
    'ios',
    async (config) => {
      const projectRoot = config.modRequest.projectRoot;
      const sourceRoot = IOSConfig.Paths.getSourceRoot(projectRoot);

      const srcDir = path.join(projectRoot, SOURCE_DIR_NAME);
      const destDir = path.join(
        sourceRoot,
        'Images.xcassets',
        `${DARK_ICON_ASSET_SET_NAME}.appiconset`
      );

      await fs.promises.mkdir(destDir, { recursive: true });
      const entries = await fs.promises.readdir(srcDir);
      for (const entry of entries) {
        await fs.promises.copyFile(
          path.join(srcDir, entry),
          path.join(destDir, entry)
        );
      }

      return config;
    },
  ]);

  config = withInfoPlist(config, (config) => {
    const existing =
      (config.modResults.CFBundleIcons as Record<string, unknown>) ?? {};
    const existingAlternates =
      (existing.CFBundleAlternateIcons as Record<string, unknown>) ?? {};

    config.modResults.CFBundleIcons = {
      ...existing,
      CFBundleAlternateIcons: {
        ...existingAlternates,
        [DARK_APP_ICON_NAME]: {
          CFBundleIconName: DARK_ICON_ASSET_SET_NAME,
        },
      },
    };
    return config;
  });

  // Without this, App Store Connect's own binary validation rejects the
  // build with ITMS-90895 ("No such asset is present in the asset
  // catalog") even though the .appiconset is right there in Images.xcassets
  // — Xcode only treats a catalog entry as a real, CFBundleIconName-
  // resolvable alternate icon once it is also declared here, the same way
  // its own "+ Alternate Icon" UI would declare it.
  config = withXcodeProject(config, (config) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(
      config.modRequest.projectRoot
    );
    config.modResults.updateBuildProperty(
      'ASSETCATALOG_COMPILER_ALTERNATE_APPICON_NAMES',
      DARK_ICON_ASSET_SET_NAME,
      undefined,
      projectName
    );
    return config;
  });

  return config;
};

export default withAlternateAppIcon;
